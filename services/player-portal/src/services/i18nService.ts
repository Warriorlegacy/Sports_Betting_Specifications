let currentLang: LanguageCode = (localStorage.getItem('nexus_lang') as LanguageCode) || 'en';
const listeners: Array<(lang: LanguageCode) => void> = [];

export function setLanguage(lang: LanguageCode) {
  currentLang = lang;
  localStorage.setItem('nexus_lang', lang);
  listeners.forEach((l) => l(lang));
}

export function getLanguage(): LanguageCode {
  return currentLang;
}

export function t(key: string): string {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

export function useI18n() {
  const [lang, setLangState] = useState<LanguageCode>(currentLang);

  useEffect(() => {
    const handler = (newLang: LanguageCode) => setLangState(newLang);
    listeners.push(handler);
    return () => {
      const idx = listeners.indexOf(handler);
      if (idx !== -1) listeners.splice(idx, 1);
    };
  }, []);

  return {
    lang,
    setLanguage,
    t: (key: string) => t(key),
    languages: SUPPORTED_LANGUAGES
  };
}
